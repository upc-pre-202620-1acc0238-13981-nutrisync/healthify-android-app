/** Un trazo del ícono: su `d` del Figma y su posición dentro de la caja de 24 dp. */
private class IconPath(val x: Float, val y: Float, val d: String, val evenOdd: Boolean = false)

private fun icon(name: String, vararg paths: IconPath): ImageVector =
    ImageVector.Builder(
        name = "Healthify.$name",
        defaultWidth = 24.dp,
        defaultHeight = 24.dp,
        viewportWidth = 24f,
        viewportHeight = 24f,
    ).apply {
        paths.forEach { path ->
            group(translationX = path.x, translationY = path.y) {
                addPath(
                    pathData = addPathNodes(path.d),
                    pathFillType = if (path.evenOdd) PathFillType.EvenOdd else PathFillType.NonZero,
                    fill = SolidColor(IconFill),
                )
            }
        }
    }.build()
